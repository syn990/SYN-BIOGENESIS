"""Writes src/colour/io/bgw_classes.h: how Color Mod's Organism,
GeneticCode and Gene are serialized in its world files, from the same
class model the translation uses.

For each class: the field descriptors in ObjectStreamClass's order
(primitives, then objects, each sorted by name; static and transient
fields left out), and a writer and a reader that move every field between
the C struct and the Java object graph of src/io/jser.h. The helpers they
call (w_color, r_code, ...) are src/colour/io/bgw.c's."""

import j2c_spec as SPEC
from j2c_emit import HEADER

PRIM = {'int': 'I', 'double': 'D', 'boolean': 'Z', 'long': 'J', 'float': 'F', 'byte': 'B',
        'char': 'C', 'short': 'S'}
OBJ_SIG = {'String': 'Ljava/lang/String;', 'Color': 'Ljava/awt/Color;',
           'GeneticCode': 'Lbiogenesis/GeneticCode;', 'Gene': 'Lbiogenesis/Gene;',
           'World': 'Lbiogenesis/World;', 'Rectangle': 'Ljava/awt/Rectangle;'}
ARR_SIG = {'int': '[I', 'double': '[D', 'Color': '[Ljava/awt/Color;',
           'Gene': '[Lbiogenesis/Gene;'}

CLASSES = [('Gene', 'gene', None), ('GeneticCode', 'code', None),
           ('Organism', 'organism', '&c_rect')]


def stream_fields(cls):
    """(type code, Java name, signature, Field) in stream order."""
    out = []
    for f in cls.fields.values():
        if f.static or 'transient' in f.node.mods:
            continue
        t = f.type
        if t.dims == 0 and t.base in PRIM:
            out.append((PRIM[t.base], f.name, None, f))
        elif t.dims == 0 and t.base in OBJ_SIG:
            out.append(('L', f.name, OBJ_SIG[t.base], f))
        elif t.dims == 1 and t.base in ARR_SIG:
            out.append(('[', f.name, ARR_SIG[t.base], f))
        else:
            raise SystemExit(f'bgw: no serialized form for {cls.name}.{f.name} ({t})')
    prims = sorted((x for x in out if x[0] not in 'L['), key=lambda x: x[1])
    objs = sorted((x for x in out if x[0] in 'L['), key=lambda x: x[1])
    return prims + objs


def writer(cls, short, fields):
    ctype = cls.name
    lines = [f'static void w_{short}_fields(Out *o, JObj *x, const {ctype} *s)', '{']
    for code, name, sig, f in fields:
        m = f's->{f.cname}'
        t = f.type
        if code in 'IZJBSC':
            v = f'vi({m})'
        elif code == 'D':
            v = f'vd({m})'
        elif t.dims == 0:
            v = {'String': f'vo(w_string(o, {m}))', 'Color': f'vo(w_color(o, {m}))',
                 'GeneticCode': f'vo(w_code(o, {m}))', 'Gene': f'vo(w_gene(o, {m}))',
                 'World': 'vo(o->world)', 'Rectangle': f'vo(w_rect(o, &{m}))'}[t.base]
        else:
            v = {'int': f'vo(w_ints(o, {m}))', 'double': f'vo(w_doubles(o, {m}))',
                 'Color': f'vo(w_colors(o, {m}))', 'Gene': f'vo(w_genes(o, {m}))'}[t.base]
        lines.append(f'    jobj_set(x, "{name}", {v});')
    lines += ['}', '']
    return lines


def reader(cls, short, fields):
    ctype = cls.name
    lines = [f'static void r_{short}_fields(In *in, const JObj *x, {ctype} *s)', '{']
    for code, name, sig, f in fields:
        m = f's->{f.cname}'
        t = f.type
        if code in 'IJBSC':
            lines.append(f'    {m} = ({SPEC.ctype(t)})r_i(in, x, "{name}", \'{code}\');')
        elif code == 'Z':
            lines.append(f'    {m} = r_i(in, x, "{name}", \'Z\') != 0;')
        elif code == 'D':
            lines.append(f'    {m} = r_d(in, x, "{name}");')
        elif t.dims == 0:
            lines.append({
                'String': f'    {m} = r_string(in, x, "{name}");',
                'Color': f'    {m} = r_color(in, x, "{name}");',
                'GeneticCode': f'    {m} = r_code(in, r_o(in, x, "{name}"));',
                'Gene': f'    {m} = r_gene(in, r_o(in, x, "{name}"));',
                'World': f'    {m} = in->w; /* "{name}": the world being read */',
                'Rectangle': f'    r_rect(in, r_o(in, x, "{name}"), &{m});'}[t.base])
        else:
            lines.append({
                'int': f'    {m} = r_ints(in, x, "{name}");',
                'double': f'    {m} = r_doubles(in, x, "{name}");',
                'Color': f'    {m} = r_colors(in, x, "{name}");',
                'Gene': f'    {m} = r_genes(in, x, "{name}");'}[t.base])
    lines += ['}', '']
    return lines


def generate(classes, out_path):
    out = [HEADER.format(java='Organism.java, GeneticCode.java and Gene.java'),
           '/* How Color Mod serializes its organisms, genetic codes and genes',
           ' * (generated by tools/colour/j2c_bgw.py; included by bgw.c). */',
           '#ifndef COLOUR_IO_BGW_CLASSES_H', '#define COLOUR_IO_BGW_CLASSES_H', '']
    for jname, short, sup in CLASSES:
        cls = classes[jname]
        fields = stream_fields(cls)
        out.append(f'static const JField f_{short}[] = {{')
        for code, name, sig, f in fields:
            out.append(f'    F(\'{code}\', "{name}"),' if sig is None else
                       f'    FO(\'{code}\', "{name}", "{sig}"),')
        out.append('};')
        out.append(f'static const JClass c_{short} = {{"biogenesis.{jname}", U_FILE_VERSION, 0x02, '
                   f'{len(fields)}, f_{short}, {sup or "NULL"}}};')
        out.append('')
    for jname, short, sup in CLASSES:
        cls = classes[jname]
        fields = stream_fields(cls)
        out += writer(cls, short, fields)
        out += reader(cls, short, fields)
    out.append('#endif')
    with open(out_path, 'w') as fh:
        fh.write('\n'.join(out) + '\n')
